#!/usr/bin/env python3
"""How system trays work on Linux today, one SVG: a lecture before Maia gets its own tray.

    python3 <path>/linux_system_tray.py              (from any directory)

writes linux-system-tray.svg into the current directory. From the top:

    1. the two generations: XEmbed (X11, the application draws) and StatusNotifierItem (D-Bus, the
       application describes, the panel draws)
    2. StatusNotifierItem: the three roles (item, watcher, host) and the menu, who calls whom
    3. the reference: properties, methods, signals of the interfaces
    4. who implements it, how to use it well, and what it means for Maia

Not Maia's design: the protocols as they are. svgkit.py draws the shapes.
"""

import os
import sys
import textwrap

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import svgkit  # noqa: E402
from svgkit import PROCESS_CHILD, PROCESS_CLIENT, PROCESS_MAIA, PROCESS_SYSTEM, Rect, Svg  # noqa: E402

svgkit.ARROW.clear()
svgkit.ARROW.update({
    "dbus": ("#2563eb", False, "D-Bus method call (and its answer)"),
    "signal": ("#7c3aed", True, "D-Bus signal: sent by the object, heard by whoever listens"),
    "x11": ("#b45309", False, "X11: client messages, a window reparented (XEmbed)"),
})
svgkit.KIND.update({
    "iface": ("D-Bus interface", "#2563eb"),
    "name": ("bus name", "#0f766e"),
})

W = 2600
CH = 6.1  # average width of a character of 12 px text


def wrap(text, width, size=12.5):
    return textwrap.wrap(text, max(10, int(width / (size * 0.5))), break_long_words=False, break_on_hyphens=False)


def paragraph(s, x, y, w, text, size=12.5, fill="#1e293b", bullet=False):
    lines = wrap(text, w - (16 if bullet else 0), size)
    for i, line in enumerate(lines):
        if bullet and i == 0:
            s.text(x, y, "•", size=size, weight="bold", fill="#475569")
        s.text(x + (16 if bullet else 0), y, line, size=size, fill=fill)
        y += size + 4.5
    return y


def bullets(s, x, y, w, items, size=12.5):
    for item in items:
        if isinstance(item, tuple):
            head, text = item
            s.text(x, y, head, size=size + 0.5, weight="bold", fill="#0f172a")
            y += size + 6
            y = paragraph(s, x, y, w, text, size)
        else:
            y = paragraph(s, x, y, w, item, size, bullet=True)
        y += 6
    return y


def section(s, y, number, title, subtitle):
    s.add(f'<rect x="40" y="{y}" width="{W - 80}" height="54" rx="10" fill="#0f172a"/>')
    s.text(64, y + 35, f"{number}  {title}", size=22, weight="bold", fill="#ffffff")
    s.text(W - 64, y + 34, subtitle, size=14, fill="#cbd5e1", anchor="end")
    return y + 54


def card(s, x, y, w, title, kind, lines, path=None):
    wrapped = []
    for line in lines:
        wrapped.extend(wrap(line, w - 34, 12) or [""])
    return s.card(x, y, w, title, kind, wrapped, path)


def frame(s, x, y, w, title, subtitle, color, cards, path=None, top=58):
    """A process with its cards stacked inside; returns (frame rect, card rects)"""
    rects = []
    cy = y + top + (16 if path else 0)
    for title_, kind, lines, cpath in cards:
        r = card(s, x + 14, cy, w - 28, title_, kind, lines, cpath)
        rects.append(r)
        cy = r.bottom + 12
    rect = Rect(x, y, w, cy - y + 4)
    s.process(rect, title, subtitle, color, path)
    # The cards were drawn before the frame: draw them again on top
    for (title_, kind, lines, cpath), r in zip(cards, rects):
        card(s, r.x, r.y, r.w, title_, kind, lines, cpath)
    return rect, rects


def legend(s, x, y, w):
    h = 250
    s.add(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="12" fill="#f8fafc" stroke="#cbd5e1" stroke-width="1.5"/>')
    s.text(x + 18, y + 28, "Legend", size=17, weight="bold")
    cy = y + 50
    for color, text in [(PROCESS_SYSTEM, "a process of the system or of a desktop (a panel, a daemon)"),
                        (PROCESS_CLIENT, "an application with a tray icon"),
                        (PROCESS_CHILD, "a helper process"),
                        (PROCESS_MAIA, "what Maia would add")]:
        s.add(f'<rect x="{x + 18}" y="{cy}" width="42" height="16" rx="4" fill="{color}"/>')
        s.text(x + 72, cy + 13, text, size=12.5)
        cy += 24
    cy += 6
    for kind, (color, dashed, text) in svgkit.ARROW.items():
        s.arrow([(x + 18, cy + 6), (x + 60, cy + 6)], kind)
        s.text(x + 72, cy + 10, text, size=12.5)
        cy += 24
    s.text(x + 18, cy + 12, "Numbers on the arrows: the order of what happens (section 2).", size=12, fill="#475569",
           italic=True)


def header(s):
    s.text(40, 62, "System trays on Linux — how they work today", size=34, weight="bold")
    s.text(40, 94, "the protocols as they are (2026-11): XEmbed, StatusNotifierItem, com.canonical.dbusmenu · "
           "generated by doc/diagrams/linux_system_tray.py", size=14, fill="#475569")
    y = 136
    y = paragraph(s, 40, y, 1700, "A tray icon is a small, lasting sign of a program in the panel: a chat with new "
                  "messages, a cloud folder syncing, a game client running without a window. Linux has had two ways to "
                  "do it. The old one lets the application put a window of its own into the panel; it works only on X11. "
                  "The one in use today, StatusNotifierItem, makes the application describe its icon over D-Bus and "
                  "lets the panel draw it, the menu included: it works on Wayland, follows the theme and the scale, and "
                  "a panel can show it however it likes (in a bar, in a list, in a Control Center).", size=14)
    y += 10
    y = paragraph(s, 40, y, 1700, "Three roles share the work: the item (the application's icon), the watcher (a "
                  "registry, one per session) and the host (the panel that shows the icons). A session without a "
                  "watcher has no tray: applications look for one at their start and do something else when there is "
                  "none (an X11 icon, a window, nothing at all).", size=14)
    legend(s, 1820, 40, 740)
    return max(y, 300) + 10


# --- 1. Two generations ---

def generations(s, y):
    y = section(s, y, "1", "Two generations of the tray", "XEmbed: the application draws · StatusNotifierItem: "
                "the application describes, the panel draws")
    y += 24
    pw = (W - 80 - 30) / 2
    top = y
    # --- XEmbed ---
    x = 40
    s.text(x + 18, y + 30, "XEmbed — the System Tray Protocol (freedesktop, 2002)", size=17, weight="bold")
    dy = y + 56
    panel = Rect(x + 24, dy, 360, 132)
    s.process(panel, "The panel (an X11 client)", "the tray manager", PROCESS_SYSTEM)
    paragraph(s, panel.x + 16, dy + 76, panel.w - 32, "owns the selection _NET_SYSTEM_TRAY_S<screen>: the sign that a "
              "tray exists; a window that takes icons in", size=12)
    app = Rect(x + pw - 24 - 360, dy, 360, 132)
    s.process(app, "An application", "old GTK 2, Java, Wine", PROCESS_CLIENT)
    paragraph(s, app.x + 16, dy + 76, app.w - 32, "a tiny X11 window of its own: it draws the icon itself and handles "
              "the clicks and its menu itself", size=12)
    s.arrow([(app.x, dy + 50), (panel.right, dy + 50)], "x11", label="1  ClientMessage _NET_SYSTEM_TRAY_OPCODE:\n"
            "    SYSTEM_TRAY_REQUEST_DOCK (its window)", label_at=(panel.right + 20, dy + 26))
    s.arrow([(panel.right, dy + 104), (app.x, dy + 104)], "x11", label="2  reparents that window into itself (XEmbed)",
            label_at=(panel.right + 20, dy + 94))
    by = dy + 160
    by = bullets(s, x + 24, by, pw - 48, [
        "X11 only: Wayland has no such thing as one client's window inside another's. Under Wayland these icons work "
        "only for X11 programs (Xwayland), through a bridge (xembedsniproxy, below).",
        "The panel gets pixels it cannot restyle: no theme colours, blurry on a scaled screen, invisible on a dark "
        "panel; no tooltip or status it could read; nothing for screen readers.",
        "Every application draws its own menu, at its own place, in its own look.",
        "Still met in: Java (AWT SystemTray), Wine, very old GTK programs. Qt uses it only when there is no "
        "StatusNotifierItem host.",
    ])
    left_h = by - top
    # --- StatusNotifierItem ---
    x = 40 + pw + 30
    s.text(x + 18, y + 30, "StatusNotifierItem (SNI) — KDE, 2009; the standard in use today", size=17, weight="bold")
    by = bullets(s, x + 24, y + 62, pw - 48, [
        ("The idea", "The application exports a D-Bus object that describes its icon: a name from the icon theme (or "
         "pixmaps), a tooltip, a status (passive, active, needs attention) and a menu. The panel reads it and draws "
         "it its own way, and calls the application back when the user clicks."),
        ("What it gives", "Works on Wayland and X11 alike; icons from the theme, sharp at any scale, light or dark as "
         "the panel needs; a status the panel can act on (hide passive icons, show those that need attention); one "
         "menu protocol for every program (com.canonical.dbusmenu), drawn by the panel; tooltips; accessible text."),
        ("The names", "Proposed to freedesktop.org but never finished there: the interfaces everybody uses are named "
         "org.kde.StatusNotifierItem, org.kde.StatusNotifierWatcher, org.kde.StatusNotifierHost. Canonical's "
         "AppIndicator (libayatana-appindicator) is SNI with its own library."),
        ("Who speaks it", "KDE Plasma, Qt (QSystemTrayIcon), KDE Frameworks (KStatusNotifierItem), Electron and "
         "Chromium, AppIndicator for GTK, waybar, Xfce, LXQt, GNOME with an extension (section 4)."),
    ])
    right_h = by - top
    h = max(left_h, right_h) + 10
    for px in (40, 40 + pw + 30):
        s.add(f'<rect x="{px}" y="{top}" width="{pw}" height="{h}" rx="12" fill="none" stroke="#cbd5e1" stroke-width="1.5"/>')
    return top + h


# --- 2. The roles of StatusNotifierItem ---

def roles(s, y):
    y = section(s, y, "2", "StatusNotifierItem: three roles and a menu, on the session bus",
                "the numbers are the order in which things happen")
    y += 24
    bus = s.bus(40, y, W - 80, "session D-Bus  ($DBUS_SESSION_BUS_ADDRESS)", [
        "every role is an ordinary D-Bus client of the user's session bus; nothing is on the system bus"], color="#2563eb")
    y = bus.bottom + 34
    AX, AW = 40, 700
    WX, WW = 940, 660
    HX, HW = 1840, 720
    for x, w, title, sub in [(AX, AW, "The item", "the application: one D-Bus object per icon"),
                             (WX, WW, "The watcher", "a registry: exactly one per session"),
                             (HX, HW, "The host", "the panel: draws every registered item")]:
        s.column_title(x, y, w, title, sub)
    y += 50
    app, (aname, item, menu) = frame(s, AX, y, AW, "An application", "e.g. Nextcloud, Discord, Steam, KDE Connect",
                                     PROCESS_CLIENT, [
        ("Its bus name", "name", [
            "org.kde.StatusNotifierItem-<pid>-<n>, or only its unique name (:1.42): the watcher takes whatever it "
            "is given",
            "when the name goes (the program quits or crashes), the icon goes"],
         None),
        ("The item object", "iface", [
            "properties: Id, Category, Title, Status, IconName or IconPixmap, OverlayIcon…, AttentionIcon…, "
            "ToolTip, Menu, ItemIsMenu, IconThemePath, WindowId",
            "methods: Activate(x, y), SecondaryActivate(x, y), ContextMenu(x, y), Scroll(delta, orientation), "
            "ProvideXdgActivationToken(token)",
            "signals: NewIcon, NewStatus, NewToolTip, NewTitle, NewAttentionIcon, NewOverlayIcon"],
         "/StatusNotifierItem   org.kde.StatusNotifierItem"),
        ("The menu object", "iface", [
            "the menu as a tree of items with ids: label, icon, enabled, visible, check or radio, shortcut, submenus",
            "the host asks for the tree (GetLayout), says what the user did (Event), and hears LayoutUpdated, "
            "ItemsPropertiesUpdated"],
         "the path in the item's Menu property   com.canonical.dbusmenu"),
    ])
    watcher, (wreg, wlife) = frame(s, WX, y, WW, "The watcher", "Plasma: a module of kded6 (statusnotifierwatcher), "
                                   "loaded by itself", PROCESS_SYSTEM, [
        ("The registry", "iface", [
            "RegisterStatusNotifierItem(service), RegisterStatusNotifierHost(service)",
            "RegisteredStatusNotifierItems, IsStatusNotifierHostRegistered, ProtocolVersion (properties)",
            "StatusNotifierItemRegistered / Unregistered, StatusNotifierHostRegistered / Unregistered (signals)"],
         "/StatusNotifierWatcher   org.kde.StatusNotifierWatcher"),
        ("Keeping it true", "system", [
            "listens to NameOwnerChanged: an item or host whose bus name vanished is dropped, and the others are told",
            "applications ask it at their start whether a host exists; without a watcher they fall back (X11 icon, "
            "a window, nothing)"], None),
    ])
    host, (hname, hread, hdraw, hclick, hmenu) = frame(s, HX, y, HW, "The host", "the panel: Plasma's system tray, "
                                                       "waybar, Xfce, …", PROCESS_SYSTEM, [
        ("Its bus name", "name", ["org.kde.StatusNotifierHost-<pid>: only so that the watcher knows a host is there"],
         None),
        ("Reads every item", "system", [
            "GetAll on the item's properties when it appears, then only what its New… signals say changed"], None),
        ("Draws it", "system", [
            "the icon by name from the theme (IconThemePath first), or the best-sized pixmap; the overlay on top",
            "Passive: may go into an overflow; NeedsAttention: the attention icon, or a sign"], None),
        ("Clicks go back to the item", "system", [
            "left: Activate (or the menu when ItemIsMenu); middle: SecondaryActivate; wheel: Scroll",
            "Wayland: ProvideXdgActivationToken first, so that the program may raise its window"], None),
        ("Shows the menu itself", "system", [
            "reads the tree over dbusmenu and renders it in the panel's look; ContextMenu only for an item "
            "without one"], None),
    ])
    # 1, 2, 3: registering
    s.link(hname, wreg, "dbus", 1680, a_dy=-6, b_dy=-30, label="1  RegisterStatusNotifierHost")
    s.link(aname, wreg, "dbus", 860, label="2  RegisterStatusNotifierItem")
    s.link(wreg, hname, "signal", 1720, a_dy=22, b_dy=8, label="3  StatusNotifierItemRegistered(name)")
    # 4–7: host and item talk directly, under the watcher
    lane_y = watcher.bottom + 40
    for i, (src, dst, kind, text, ax, hx) in enumerate([
        (hread, item, "dbus", "4  GetAll: the icon, the tooltip, the status, the menu path", 820, 1760),
        (item, hread, "signal", "5  NewIcon, NewStatus, NewToolTip … (then the host reads again)", 800, 1780),
        (hclick, item, "dbus", "6  Activate(x, y) · SecondaryActivate · Scroll · ProvideXdgActivationToken", 780, 1800),
        (hmenu, menu, "dbus", "7  GetLayout, AboutToShow, Event(id, \"clicked\") · LayoutUpdated back", 760, 1820),
    ]):
        ly = lane_y + 30 * i
        if src.x > dst.x:   # from the host to the application
            pts = [(src.x, src.mid_y(-8 + 4 * i)), (hx, src.mid_y(-8 + 4 * i)), (hx, ly), (ax, ly),
                   (ax, dst.mid_y(-20 + 12 * i)), (dst.right, dst.mid_y(-20 + 12 * i))]
        else:
            pts = [(src.right, src.mid_y(-20 + 12 * i)), (ax, src.mid_y(-20 + 12 * i)), (ax, ly), (hx, ly),
                   (hx, dst.mid_y(-8 + 4 * i)), (dst.x, dst.mid_y(-8 + 4 * i))]
        s.arrow(pts, kind, label=text, label_at=(WX + 10, ly - 5))
    y = max(app.bottom, host.bottom, lane_y + 30 * 4) + 30

    # The bridge for X11 icons
    old = Rect(AX, y, 330, 120)
    s.process(old, "An X11 program", "XEmbed only (Wine, Java)", PROCESS_CLIENT)
    paragraph(s, old.x + 16, y + 78, old.w - 32, "docks a window, as in section 1", size=12)
    proxy = Rect(AX + 370, y, 330, 120)
    s.process(proxy, "xembedsniproxy", "Plasma's bridge, an X11 client", PROCESS_CHILD)
    paragraph(s, proxy.x + 16, y + 78, proxy.w - 32, "owns the X11 tray selection; makes one SNI item of each "
              "docked window (a picture of it, clicks sent back as X11 events)", size=12)
    s.arrow([(old.right, y + 60), (proxy.x, y + 60)], "x11", label="docks", label_at=(old.right + 6, y + 52))
    paragraph(s, proxy.right + 30, y + 40, 1500, "Each docked window becomes an item of its own: the bridge registers "
              "it with the watcher (arrow 2) and answers the host's calls (4–7) for it, so one host shows both kinds. "
              "It needs an X11 display (Xwayland) and an SNI host, and it is started with the session (in Plasma by "
              "autostart).", size=12.5, fill="#334155")
    return old.bottom


# --- 3. The reference ---

def reference(s, y):
    y = section(s, y, "3", "The reference: what each interface offers", "names as on the bus; the full texts: "
                "freedesktop.org StatusNotifierItem draft, libdbusmenu")
    y += 24
    cols = [
        [("org.kde.StatusNotifierItem", "properties", [
            ("Id", "a stable name of the application"),
            ("Category", "ApplicationStatus, Communications, SystemServices, Hardware"),
            ("Title", "the program's name, for lists"),
            ("Status", "Passive, Active, NeedsAttention"),
            ("WindowId", "X11 window, 0 on Wayland"),
            ("IconName, IconPixmap", "theme name; or a(iiay): w, h, ARGB32 bytes"),
            ("IconThemePath", "where its own icons are"),
            ("OverlayIconName, OverlayIconPixmap", "a small sign on top"),
            ("AttentionIconName, …Pixmap, AttentionMovieName", ""),
            ("ToolTip", "(icon name, pixmap, title, text)"),
            ("ItemIsMenu", "a left click opens the menu"),
            ("Menu", "object path of its dbusmenu"),
          ])],
        [("org.kde.StatusNotifierItem", "methods", [
            ("Activate(x, y)", "the main action (show the window)"),
            ("SecondaryActivate(x, y)", "e.g. mute, a new window"),
            ("ContextMenu(x, y)", "the item shows its own menu"),
            ("Scroll(delta, orientation)", "\"vertical\" / \"horizontal\""),
            ("ProvideXdgActivationToken(token)", "KDE, for Wayland focus"),
          ]),
         ("org.kde.StatusNotifierItem", "signals", [
            ("NewTitle, NewIcon, NewAttentionIcon", "read the property again"),
            ("NewOverlayIcon, NewToolTip", ""),
            ("NewStatus(status)", "the value comes with it"),
          ])],
        [("com.canonical.dbusmenu", "the menu", [
            ("GetLayout(parent, depth, props)", "(revision, tree of (id, props, children))"),
            ("GetGroupProperties(ids, props)", ""),
            ("AboutToShow(id)", "-> needs an update; before opening"),
            ("Event(id, \"clicked\"|\"opened\"|…, data, time)", ""),
            ("LayoutUpdated(revision, parent)", "signal: read again"),
            ("ItemsPropertiesUpdated(updated, removed)", "signal"),
            ("item properties", "type (separator), label (_ mnemonic),"),
            ("", "enabled, visible, icon-name, icon-data,"),
            ("", "toggle-type, toggle-state, shortcut,"),
            ("", "children-display \"submenu\""),
          ])],
        [("org.kde.StatusNotifierWatcher", "the registry", [
            ("RegisterStatusNotifierItem(service)", "a name or a path"),
            ("RegisterStatusNotifierHost(service)", ""),
            ("RegisteredStatusNotifierItems", "property: as"),
            ("IsStatusNotifierHostRegistered", "property: b"),
            ("ProtocolVersion", "property: i"),
            ("StatusNotifierItemRegistered(s)", "signal"),
            ("StatusNotifierItemUnregistered(s)", "signal"),
            ("StatusNotifierHostRegistered()", "signal"),
          ])],
    ]
    probe = Svg(W)
    col_w = (W - 80) / len(cols)
    heights = [sum(probe.api_block(0, 0, col_w - 40, *b) for b in c) for c in cols]
    h = 40 + max(heights)
    s.add(f'<rect x="40" y="{y}" width="{W - 80}" height="{h}" rx="12" fill="#f8fafc" stroke="#cbd5e1" stroke-width="1.5"/>')
    for i, c in enumerate(cols):
        cy = y + 34
        for block in c:
            cy += s.api_block(40 + 20 + i * col_w, cy, col_w - 40, *block)
    return y + h


# --- 4. Who, how, Maia ---

def practice(s, y):
    y = section(s, y, "4", "Who implements it, how to use it well, and Maia",
                "the rules that make icons appear and behave in every panel")
    y += 24
    cw = (W - 80 - 2 * 30) / 3
    panels = [
        ("Who implements what", [
            ("Applications (items)", "Qt: QSystemTrayIcon speaks SNI when a host is registered, else XEmbed. KDE: "
             "KStatusNotifierItem. GTK 3: libayatana-appindicator (GtkStatusIcon is XEmbed, gone in GTK 4). Electron "
             "and Chromium: their own SNI. Rust: ksni. Java AWT, Wine: XEmbed."),
            ("Panels (hosts) and watchers", "Plasma: the watcher is a kded6 module, the host is plasmashell's "
             "system tray. GNOME: none by itself, the AppIndicator extension adds both. waybar, Xfce, LXQt: host and "
             "watcher. swaybar: host only. In a session of its own every desktop brings its watcher."),
        ]),
        ("Using it well", [
            ("As an application", "Use a library, not the raw interfaces. Give an icon name from the theme "
             "(and IconThemePath for your own icons), pixmaps only as a fallback and then in several sizes. Set Status "
             "honestly: Passive when there is nothing to say. Always have a menu with the main actions and Quit: "
             "some panels never send Activate. Watch IsStatusNotifierHostRegistered and the host signals: without a "
             "host, show your window instead of hiding where nobody can reach you. Accept the activation token."),
            ("As a panel or a session", "Start the watcher before the programs that autostart, or their first "
             "check finds none. Exactly one watcher: two processes trying to own the name leave icons in the wrong one. "
             "Accept an object path where a bus name is expected (libappindicator, some Electron versions do it). Drop "
             "items when their name goes. Read the icon by name first; draw the menu yourself. Coalesce bursts of "
             "New… signals. Hand an activation token to Activate on Wayland."),
        ]),
        ("In the Maia session", [
            ("Today", "Nobody owns org.kde.StatusNotifierWatcher (checked 2026-11-26): kded6 is started only on demand "
             "and its watcher module with it, and Maia has no host. So icons do not appear, and programs that "
             "close to the tray cannot be brought back."),
            ("What a Maia tray needs", "A service of the session that owns the watcher name and is the one host "
             "(TODO.md item 4): it tracks the items, reads their icons, tooltips and menus, and gives them to the "
             "frontends over Cap'n Proto, so that Lumen's taskbar and the Maia frontend draw the same items their own "
             "way; clicks, scrolling and menu events go back through it, with an activation token. It starts early in "
             "session.toml. kded6's statusnotifierwatcher module is switched off in Maia's kded6rc (as "
             "networkmanagement already is), and xembedsniproxy starts with the session for X11 icons."),
        ]),
    ]
    tops = []
    probe = Svg(W)
    heights = []
    for title, items in panels:
        heights.append(bullets(probe, 0, 60, cw - 40, items) - 0)
    h = max(heights) + 20
    for i, (title, items) in enumerate(panels):
        x = 40 + i * (cw + 30)
        color = "#ede9fe" if i == 2 else "#f8fafc"
        stroke = PROCESS_MAIA if i == 2 else "#cbd5e1"
        s.add(f'<rect x="{x}" y="{y}" width="{cw}" height="{h}" rx="12" fill="{color}" fill-opacity="0.6" '
              f'stroke="{stroke}" stroke-width="1.5"/>')
        s.text(x + 20, y + 32, title, size=17, weight="bold", fill="#5b21b6" if i == 2 else "#0f172a")
        bullets(s, x + 20, y + 62, cw - 40, items)
        tops.append(x)
    return y + h


def main():
    s = Svg(W)
    y = header(s)
    y = generations(s, y + 20)
    y = roles(s, y + 40)
    y = reference(s, y + 40)
    y = practice(s, y + 40)
    out = os.path.join(os.getcwd(), "linux-system-tray.svg")
    with open(out, "w", encoding="utf-8") as f:
        f.write(s.render(y + 40))
    print(out)


if __name__ == "__main__":
    main()
